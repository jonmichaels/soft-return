// LaserJetTables.swift
//
// WS7's LASERJET printer driver, as data: its font list and the width and kerning tables of
// its proportional fonts (WordStar 7's printer description LASERJET.PDF, run by DRIVERN; read
// in the WS7 teardown, `wordstar-dos/11-print-engine.md` 11.17). `LaserJet.swift` runs them.
// Port of ctrl-kd's `laserjet_tables.py`, generated from it; edit that file and regenerate,
// never this one by hand.
//
// - `fonts`: the driver's fonts in its own order: the width field (1/8192 em for a scalable
//   font), the height in twips (0 for a scalable font), the typestyle key a document's font
//   record is matched against, and the block of each variant, (normal, italic, bold,
//   bold italic).
// - `blocks`: each proportional block. A width is in design units, `em` to the em; one point
//   is `num`/`den` inch on this font's scale (100/7231 for the Intellifont faces, 1/72 for
//   the TrueType ones, which round pixels per em first: `ppemFirst`); the printer has `unit`
//   dots to the inch. `script` is a sub/superscript's size in 1/256 of the line's (0:
//   unscaled). `widths` has 256 entries by printer character code (PC-8). `kern` maps a
//   first character code to `[second: amount]`, in 1/128 em, signed.

enum LaserJetTables {
    /// One driver font: `(name, width, height, key, blocks)`.
    struct Font {
        let name: String
        let width: Int
        let height: Int
        let key: Int
        let blocks: [String]
    }

    /// One proportional block. A class so that two spans can ask whether they share one
    /// (`===`), as the Python twin compares `id(block)`.
    final class Block {
        let em: Int
        let num: Int
        let den: Int
        let unit: Int
        let ppemFirst: Bool
        let script: Int
        let widths: [Int]
        let kern: [Int: [Int: Int]]

        init(em: Int, num: Int, den: Int, unit: Int, ppemFirst: Bool, script: Int,
             widths: [Int], kern: [(Int, Int, Int)]) {
            self.em = em
            self.num = num
            self.den = den
            self.unit = unit
            self.ppemFirst = ppemFirst
            self.script = script
            self.widths = widths
            var map: [Int: [Int: Int]] = [:]
            for (first, second, amount) in kern { map[first, default: [:]][second] = amount }
            self.kern = map
        }
    }

