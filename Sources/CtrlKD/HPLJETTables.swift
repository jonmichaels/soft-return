// HPLJETTables.swift
//
// WS4's HPLJET printer driver, as data: its width tables, font records, font maps and
// character translation (WordStar 4.00's WSPRINT.OVR, driver HPLJET; read in the WS4
// teardown, `wordstar4-dos/4-formatting-printing.md` 15). `HPLJET.swift` runs them. Port
// of ctrl-kd's `hpljet_tables.py`, generated from it; edit that file and regenerate, never
// this one by hand.
//
// - `ps`: the five proportional width tables, 256 widths each by printer character code,
//   in 1/600 inch.
// - `fonts`: the 19 font records: the cell width `w` in 1/`den` inch (a fixed font's
//   pitch; 5/600 = 1/120 inch for a proportional one) and the width table, nil for a
//   fixed font.
// - `fontmapFixed` / `fontmapPS`: `.CW` 0-30 to `(record, extra)`. A fixed font advances
//   `w + extra`; a `fontmapPS` record with 0x40 or 0x80 set has italic and bold records
//   after it (record + 1, + 2).
// - `compos`: CP437 to the LaserJet's Roman-8, `(first, second)`; a second byte is printed
//   over the first.
// - `roman8`: Python's `hp_roman8` codec, the LaserJet's Roman-8 code to Unicode (nil
//   where the codec has no character), and its inverse.

